#!/usr/bin/env python3
"""Bounded MIPS journal of observed, provenance-bound producer events.

capture(a0=event, a1=live producer SP, a2=actual result,
        a3=wrapper-owned [statement, destination, ordinal, mode]) records raw
ROW/TERMINAL/RESET/END evidence and returns no authority/status. Unsupported
mode and zero producer ticket are ignored. Nonzero tickets require the private
lineage validator and exact frame/statement/destination/offset agreement before
any descriptor/count read. No saved native pointer is followed later.

The journal is append-only, never reused, and permanently faults on allocation
loss or protocol/association failure. A record's magic is published last. Both
the journal and lineage global fault states override all published records.
Reservation/publication order is not native mutation order; validation is not
a lease. Raw duplicate/gap/terminal/reset/completeness checks belong to the
decoder. There is no per-producer progress, completed-row object, owner epoch,
whole-folder authority, UI action, runtime allocation, timer, export or I/O.
RESET is the actual 0x5C31C0 statement-reset return. The separate wrapper
finalization at 0x5C30E0 runs after producer END and is not captured here.

Only capture makes the explicitly bounded native reads, from the current
producer frame and current actual destination. The wrapper supplies a live
owned metadata block. Their lifetime/source-coverage premises are NOT proved
by pointer equality or these instructions. The only linked external target is
the supplied private lineage validate entry. O32 callee-saved registers, SP,
RA and HI/LO survive. All other O32 volatile registers may be clobbered.

An optional content_revision_address enables a distinct diagnostic format:
PRODUCER byte56 is its immutable start sample, and event byte60 mirrors it.
The known-boundary counter must still equal that sample before additional
native reads and before publication. Equality detects no already-active writer,
stale-started job, missed hook or later mutation; it is never currentness.
"""

from build_reveal_bridge_diag import Asm, b
import folderfollow_reveal_lineage_mips as lineage


HEADER, RECORD = 16, 0x250
STATE, FAULT = 0, 0xFFFFFFFF
MAGIC_OFFSET, MAGIC = 0, int.from_bytes(b'LROW', 'little')
KIND, PRODUCER, SEQ, FRAME, STMT, DEST, MODE = 4, 8, 12, 16, 20, 24, 28
OFFSET, ORDINAL, RESULT, CUE, TRUNCATED, COUNT, ORIGIN, RESERVED = 32, 36, 40, 44, 48, 52, 56, 60
PATH, PATH_BYTES = 64, 520
ROW, TERMINAL, RESET, END = 1, 2, 3, 4
DEFAULT_CAPACITY, RETRIES = 1024, 8
MAX_CAPACITY = (0x100000000 - HEADER) // RECORD
SYNC = 0x0000000F
CALL_FRAME = 0x40


def memory_bytes(capacity=DEFAULT_CAPACITY):
    if type(capacity) is not int or not 1 <= capacity <= MAX_CAPACITY:
        raise ValueError('capacity must fit a nonempty unsigned-32 journal')
    return HEADER + RECORD * capacity


def assemble(lineage_address, lineage_entries, journal_address, code_base,
             capacity=DEFAULT_CAPACITY, *, content_revision_address=None,
             require_origin_frontier=False):
    """Return (little-endian code bytes, labels), without I/O or installation.

    The caller supplies distinct permanent zeroed RW journal storage and RX
    code. The lineage ledger is separately allocated; its validate label is
    generated by folderfollow_reveal_lineage_mips.build_lineage. Exposed reserve
    and invalidate labels are allocation/test helpers, never readiness APIs.
    """
    size = memory_bytes(capacity)
    if type(require_origin_frontier) is not bool:
        raise ValueError('origin frontier option must be an explicit boolean')
    if require_origin_frontier and content_revision_address is None:
        raise ValueError('origin frontier requires the producer revision extension')
    try:
        validate = lineage_entries['validate']
    except (KeyError, TypeError) as error:
        raise ValueError('lineage validate entry is required') from error
    for name, value in (('lineage_address', lineage_address), ('journal_address', journal_address),
                        ('code_base', code_base), ('validate', validate)):
        if type(value) is not int or not 0 <= value <= 0xFFFFFFFC or value % 4:
            raise ValueError(name + ' must be an aligned unsigned-32 address')
    if journal_address + size > 0x100000000:
        raise ValueError('journal must not wrap the address space')
    if journal_address < lineage_address + lineage.HEADER and lineage_address < journal_address + size:
        raise ValueError('journal and lineage header must not overlap')
    if content_revision_address is not None:
        if (type(content_revision_address) is not int
                or not 0 <= content_revision_address <= 0xFFFFFFFC
                or content_revision_address % 4):
            raise ValueError('contents revision must be an aligned unsigned-32 address')
        for start, length in ((lineage_address, lineage.HEADER), (journal_address, size)):
            if start < content_revision_address + 4 and content_revision_address < start + length:
                raise ValueError('contents revision must be separate private storage')
    call_frame = CALL_FRAME if content_revision_address is None else CALL_FRAME + 0x10
    a = Asm(code_base)

    def check_revision(load=False):
        if content_revision_address is None:
            return
        if load:
            a.e(b.lw(8, 56, 2), b.sw(8, 0x40, 29))
        else:
            a.e(b.lw(8, 0x40, 29))
        a.absolute(9, content_revision_address)
        a.e(SYNC, b.lw(10, 0, 9))
        a.branch(5, 8, 10, 'capture_fault')
        a.e((10 << 16) | (10 << 11) | (31 << 6) | 2)
        a.branch(5, 10, 0, 'capture_fault')
        a.e(SYNC)

    def check_origin_frontier():
        if not require_origin_frontier:
            return
        # validate(PRODUCER) already checked this immutable private root's
        # index, publication and ancestry. No native pointer is followed.
        a.e(b.lw(8, lineage.ORIGIN, 2), b.addiu(8, 8, -1),
            (8 << 16) | (8 << 11) | (6 << 6))
        a.absolute(9, lineage_address + lineage.HEADER)
        a.e(b.r_type(8, 9, 8, 0x21), b.lw(9, lineage.KIND, 8),
            b.addiu(10, 0, lineage.RENDER))
        # INITIAL and zero/unbound renderer entries have no admitted frontier.
        # Their stock callbacks continue, but no extra row payload is read.
        a.branch(5, 9, 10, 'capture_done')
        a.e(b.lw(9, 60, 8))
        a.branch(4, 9, 0, 'capture_done')
        a.e((9 << 16) | (10 << 11) | (31 << 6) | 2)
        a.branch(5, 10, 0, 'capture_fault')
        # The actual Files worker entry must be the single known boundary
        # between the original renderer entry and this producer start.
        a.e(b.addiu(9, 9, 1), b.lw(10, 0x40, 29))
        a.branch(5, 9, 10, 'capture_fault')

    def fail_if_lineage_fault():
        a.absolute(8, lineage_address)
        a.e(b.lw(8, lineage.STATE, 8), (8 << 16) | (8 << 11) | (31 << 6) | 2)
        a.branch(5, 8, 0, 'capture_fault')

    def fail_if_journal_bad():
        a.absolute(8, journal_address)
        a.absolute(9, capacity)
        a.e(b.lw(10, STATE, 8), b.r_type(9, 10, 11, 0x2B))
        a.branch(5, 11, 0, 'capture_fault')

    a.label('capture')
    a.e(b.addiu(29, 29, -call_frame), b.sw(31, 0x3C, 29))
    for register in range(16, 23):
        a.e(b.sw(register, 0x20 + (register - 16) * 4, 29))
    a.e(b.move(16, 4), b.move(17, 5), b.move(18, 6),
        b.lw(19, 0, 7), b.lw(20, 4, 7), b.lw(21, 8, 7), b.lw(22, 12, 7))
    # This gate precedes even producer-frame ticket/offset reads.
    a.branch(5, 22, 0, 'capture_done')
    a.branch(4, 16, 0, 'capture_fault')
    a.e(b.i_type(11, 16, 8, END + 1))
    a.branch(4, 8, 0, 'capture_fault')
    fail_if_journal_bad()
    fail_if_lineage_fault()
    a.branch(4, 17, 0, 'capture_fault')
    a.e(b.i_type(12, 17, 8, 3))
    a.branch(5, 8, 0, 'capture_fault')
    a.e(b.lw(4, 0x18, 17))
    a.branch(4, 4, 0, 'capture_done')
    a.e(b.sw(4, 0x10, 29), b.addiu(5, 0, lineage.PRODUCER))
    a.jump(validate, True)
    a.branch(4, 2, 0, 'capture_fault')
    for field, register in ((lineage.STACK, 17), (lineage.STMT, 19), (lineage.DEST, 20)):
        a.e(b.lw(8, field, 2))
        a.branch(5, 8, register, 'capture_fault')
    check_revision(load=True)
    check_origin_frontier()
    a.branch(4, 19, 0, 'capture_fault')
    a.branch(4, 20, 0, 'capture_fault')
    a.e(b.i_type(12, 20, 8, 3))
    a.branch(5, 8, 0, 'capture_fault')
    a.e(b.lw(8, lineage.OFFSET, 2), b.lw(9, 0xAD8, 17))
    a.branch(5, 8, 9, 'capture_fault')
    a.e(b.sw(9, 0x1C, 29), b.lw(8, lineage.ORIGIN, 2), b.sw(8, 0x14, 29))
    fail_if_lineage_fault()
    a.jump('reserve', True)
    a.branch(4, 2, 0, 'capture_done')
    a.e(b.sw(2, 0x18, 29))
    for register, offset in ((16, KIND), (3, SEQ), (17, FRAME), (19, STMT),
                             (20, DEST), (22, MODE), (21, ORDINAL), (18, RESULT)):
        a.e(b.sw(register, offset, 2))
    for local, offset in ((0x10, PRODUCER), (0x14, ORIGIN), (0x1C, OFFSET)):
        a.e(b.lw(8, local, 29), b.sw(8, offset, 2))
    if content_revision_address is not None:
        a.e(b.lw(8, 0x40, 29), b.sw(8, RESERVED, 2))
    check_revision()
    # First native object read after all lineage/frame/scalar checks.
    a.label('capture_count')
    a.e(b.lw(8, 0xC, 20), b.sw(8, COUNT, 2), b.addiu(8, 0, ROW))
    a.branch(5, 16, 8, 'capture_publish')
    a.e(b.lw(8, 0x444, 17), b.sw(8, CUE, 2),
        b.addiu(9, 17, 0x24), b.addiu(10, 2, PATH), b.addiu(11, 0, 259))
    a.label('capture_path')
    a.e(b.lhu(8, 0, 9))
    a.branch(4, 8, 0, 'capture_publish')
    a.branch(4, 11, 0, 'capture_truncated')
    a.e(b.sh(8, 0, 10), b.addiu(9, 9, 2), b.addiu(10, 10, 2), b.addiu(11, 11, -1))
    a.jump('capture_path')
    a.label('capture_truncated')
    a.e(b.addiu(8, 0, 1), b.sw(8, TRUNCATED, 2))
    a.label('capture_publish')
    a.e(SYNC)
    fail_if_lineage_fault()
    fail_if_journal_bad()
    check_revision()
    a.e(b.lw(2, 0x18, 29), SYNC)
    a.absolute(8, MAGIC)
    a.label('capture_magic_store')
    a.e(b.sw(8, MAGIC_OFFSET, 2), SYNC)
    a.jump('capture_done')
    a.label('capture_fault')
    a.jump('invalidate', True)
    a.label('capture_done')
    for register in range(16, 23):
        a.e(b.lw(register, 0x20 + (register - 16) * 4, 29))
    a.e(b.lw(31, 0x3C, 29), b.addiu(29, 29, call_frame), b.move(2, 0),
        b.r_type(31, 0, 0, 8), 0)

    a.label('reserve')
    a.absolute(8, journal_address)
    a.absolute(9, capacity)
    a.e(b.addiu(14, 0, RETRIES), SYNC)
    a.label('reserve_ll')
    a.e(b.i_type(0x30, 8, 10, STATE), b.r_type(10, 9, 11, 0x2B))
    a.branch(4, 11, 0, 'reserve_fault')
    a.e(b.addiu(3, 10, 1), b.move(11, 3))
    a.label('reserve_sc')
    a.e(b.i_type(0x38, 8, 11, STATE))
    a.branch(5, 11, 0, 'reserve_success')
    a.e(b.addiu(14, 14, -1))
    a.branch(5, 14, 0, 'reserve_ll')
    a.jump('reserve_fault')
    a.label('reserve_success')
    # Record index * 592 = index * (512 + 64 + 16), without HI/LO.
    for register, shift in ((11, 9), (12, 6), (13, 4)):
        a.e((10 << 16) | (register << 11) | (shift << 6))
    a.e(b.r_type(11, 12, 11, 0x21), b.r_type(11, 13, 11, 0x21),
        b.r_type(8, 11, 2, 0x21), b.addiu(2, 2, HEADER), SYNC,
        b.lw(11, MAGIC_OFFSET, 2))
    a.branch(5, 11, 0, 'reserve_fault')
    a.e(b.lw(10, STATE, 8), b.r_type(9, 10, 11, 0x2B))
    a.branch(5, 11, 0, 'reserve_fault')
    a.e(SYNC, b.r_type(31, 0, 0, 8), 0)
    a.label('invalidate')
    a.absolute(8, journal_address)
    a.label('reserve_fault')
    a.e(b.addiu(11, 0, -1), SYNC)
    a.label('fault_store')
    a.e(b.sw(11, STATE, 8), SYNC, b.move(2, 0), b.move(3, 0),
        b.r_type(31, 0, 0, 8), 0)

    code = a.finish()
    end = code_base + len(code)
    if (end > 0x100000000 or code_base >> 28 != (end - 1) >> 28
            or code_base >> 28 != validate >> 28):
        raise ValueError('journal code and private validate must share one MIPS jump region')
    for start, length in ((journal_address, size), (lineage_address, lineage.HEADER)):
        if start < end and code_base < start + length:
            raise ValueError('private data and journal code must not overlap')
    if code_base <= validate < end or journal_address <= validate < journal_address + size:
        raise ValueError('private validate must be distinct code')
    if (content_revision_address is not None
            and code_base < content_revision_address + 4
            and content_revision_address < end):
        raise ValueError('contents revision must be outside emitted code')
    return code, a.labels
